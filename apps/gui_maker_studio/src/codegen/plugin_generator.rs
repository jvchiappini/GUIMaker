//! Plugin-based code generator for GUIMaker
//!
//! This module provides a plugin-based code generation system that allows
//! custom code generators to be registered via the plugin system.

use crate::plugin::{CodegenConfig, CodegenGenerator, OutputFormat, PluginError};
use crate::scene::SceneState;

/// Plugin-based code generator that delegates to registered plugins
pub struct PluginCodeGenerator {
    generators: std::collections::HashMap<OutputFormat, Box<dyn CodegenGenerator>>,
}

impl PluginCodeGenerator {
    pub fn new() -> Self {
        Self {
            generators: std::collections::HashMap::new(),
        }
    }
    
    pub fn register_generator(
        &mut self,
        format: OutputFormat,
        generator: Box<dyn CodegenGenerator>,
    ) -> Result<(), PluginError> {
        if self.generators.contains_key(&format) {
            return Err(PluginError::AlreadyRegistered(format!("{:?}", format)));
        }
        self.generators.insert(format, generator);
        Ok(())
    }
    
    pub fn get_generator(&self, format: &OutputFormat) -> Option<&Box<dyn CodegenGenerator>> {
        self.generators.get(format)
    }
    
    pub fn list_formats(&self) -> Vec<OutputFormat> {
        self.generators.keys().cloned().collect()
    }
}

impl CodegenGenerator for PluginCodeGenerator {
    fn generate(&self, scene: &SceneState, config: &CodegenConfig) -> Result<String, PluginError> {
        if let Some(generator) = self.generators.get(&config.output_format) {
            generator.generate(scene, config)
        } else {
            Err(PluginError::NotFound(format!(
                "No generator registered for format: {:?}",
                config.output_format
            )))
        }
    }
    
    fn supported_formats(&self) -> Vec<OutputFormat> {
        self.list_formats()
    }
}

/// Built-in code generators that can be registered
pub mod built_in {
    use super::*;
    use crate::scene::WidgetKind;
    use ferrous_assets::Font;
    use ferrous_gui::GuiBatch;
    use ferrous_engine::AppContext;
    
    pub struct FerrousAppGenerator;
    
    impl CodegenGenerator for FerrousAppGenerator {
        fn generate(&self, scene: &SceneState, config: &CodegenConfig) -> Result<String, PluginError> {
            let mut code = String::new();
            if config.include_comments {
                code.push_str("// Generated by GUIMaker\n// Format: FerrousApp\n\n");
            }
            code.push_str(&self.generate_imports(scene, config));
            code.push_str(&self.generate_struct(scene, config));
            code.push_str(&self.generate_default(scene, config));
            code.push_str(&self.generate_ferrous_engine_impl(scene, config));
            code.push_str(&self.generate_main(scene, config));
            Ok(code)
        }
        
        fn supported_formats(&self) -> Vec<OutputFormat> {
            vec![OutputFormat::FerrousApp]
        }
    }
    
    impl FerrousAppGenerator {
        fn generate_imports(&self, _scene: &SceneState, _config: &CodegenConfig) -> String {
            "use ferrous_engine::{App, AppContext, AppMode, Color, FerrousApp, KeyCode};\nuse ferrous_assets::Font;\nuse ferrous_gui::{GuiBatch, TextBatch, Ui};\n\n".to_string()
        }
        
        fn generate_struct(&self, scene: &SceneState, _config: &CodegenConfig) -> String {
            let mut s = "struct MyApp {\n".to_string();
            for w in &scene.widgets {
                let name = format!("{}_{}", w.kind.display_name().to_lowercase().replace(" ", "_"), w.id);
                match w.kind {
                    WidgetKind::Button => s.push_str(&format!("    pub {}: Button,\n", name)),
                    WidgetKind::Slider => s.push_str(&format!("    pub {}: Slider,\n", name)),
                    WidgetKind::Checkbox => {
                        s.push_str(&format!("    pub {}: Checkbox,\n", name));
                        s.push_str(&format!("    pub {}_prev: bool,\n", name));
                    }
                    _ => {}
                }
            }
            s.push_str("}\n\n");
            s
        }
        
        fn generate_default(&self, scene: &SceneState, _config: &CodegenConfig) -> String {
            let mut s = "impl Default for MyApp {\n    fn default() -> Self {\n        Self {\n".to_string();
            for w in &scene.widgets {
                let name = format!("{}_{}", w.kind.display_name().to_lowercase().replace(" ", "_"), w.id);
                match w.kind {
                    WidgetKind::Button => s.push_str(&format!("            {}: Button::new({:.1}, {:.1}, {:.1}, {:.1}),\n", name, w.x, w.y, w.w, w.h)),
                    _ => {}
                }
            }
            s.push_str("        }\n    }\n}\n\n");
            s
        }

        fn generate_ui_methods(&self, scene: &SceneState, _config: &CodegenConfig) -> String {
            let mut s = "impl MyApp {\n    fn configure_ui(&mut self, ui: &mut Ui) {\n".to_string();
            for w in &scene.widgets {
                let name = format!("{}_{}", w.kind.display_name().to_lowercase().replace(" ", "_"), w.id);
                s.push_str(&format!("        ui.add(self.{}.clone());\n", name));
            }
            s.push_str("    }\n}\n\n");
            s
        }

        fn generate_ferrous_engine_impl(&self, scene: &SceneState, config: &CodegenConfig) -> String {
            let mut s = "impl FerrousApp for MyApp {\n".to_string();
            s.push_str("    fn update(&mut self, ctx: &mut AppContext) {\n        self.update_ui(ctx);\n    }\n");
            s.push_str("    fn draw(&mut self, ctx: &mut AppContext) {\n        // Draw\n    }\n");
            s.push_str("}\n\n");
            s
        }

        fn generate_main(&self, _scene: &SceneState, _config: &CodegenConfig) -> String {
            "fn main() {\n    App::new(MyApp::default()).run();\n}\n".to_string()
        }
        
        fn update_ui(&self, _ctx: &mut AppContext) {} // Placeholder for trait or helper
    }

    pub struct AppBuilderGenerator;
    impl CodegenGenerator for AppBuilderGenerator {
        fn generate(&self, _scene: &SceneState, _config: &CodegenConfig) -> Result<String, PluginError> {
            Ok("AppBuilder code".to_string())
        }
        fn supported_formats(&self) -> Vec<OutputFormat> { vec![OutputFormat::AppBuilder] }
    }
}
