//! Template-based code generator for GUIMaker
//!
//! Uses askama or handlebars templates to generate code.

use crate::plugin::{CodegenConfig, CodegenGenerator, OutputFormat, PluginError};
use crate::scene::{SceneState, WidgetKind};

/// Template-based code generator
pub struct TemplateCodeGenerator {
    format: OutputFormat,
}

impl TemplateCodeGenerator {
    pub fn new(format: OutputFormat) -> Self {
        Self { format }
    }
}

impl CodegenGenerator for TemplateCodeGenerator {
    fn generate(&self, scene: &SceneState, config: &CodegenConfig) -> Result<String, PluginError> {
        match self.format {
            OutputFormat::FerrousApp => self.generate_ferrous_engine(scene, config),
            OutputFormat::AppBuilder => self.generate_app_builder(scene, config),
            OutputFormat::Plugins => self.generate_plugins(scene, config),
            OutputFormat::MultiFile => self.generate_multi_file(scene, config),
        }
    }
    
    fn supported_formats(&self) -> Vec<OutputFormat> {
        vec![self.format.clone()]
    }
}

impl TemplateCodeGenerator {
    fn generate_ferrous_engine(&self, scene: &SceneState, config: &CodegenConfig) -> Result<String, PluginError> {
        let mut code = String::new();
        
        // Header
        if config.include_comments {
            code.push_str(&format!("// Generated by GUIMaker\n"));
            code.push_str(&format!("// Format: FerrousApp\n\n"));
        }
        
        // Imports
        code.push_str(&self.generate_imports(scene, config));
        
        // Struct definition
        code.push_str(&self.generate_struct(scene, config));
        
        // Default implementation
        code.push_str(&self.generate_default(scene, config));
        
        // FerrousApp implementation
        code.push_str(&self.generate_ferrous_engine_impl(scene, config));
        
        // Main function
        code.push_str(&self.generate_main(scene, config));
        
        Ok(code)
    }
    
    fn generate_app_builder(&self, scene: &SceneState, config: &CodegenConfig) -> Result<String, PluginError> {
        let mut code = String::new();
        
        if config.include_comments {
            code.push_str(&format!("// Generated by GUIMaker\n"));
            code.push_str(&format!("// Format: AppBuilder\n\n"));
        }
        
        code.push_str("use ferrous_engine::AppBuilder;\n");
        code.push_str("use ferrous_gui::{Widget, UiBuilder};\n\n");
        
        code.push_str("fn main() {\n");
        code.push_str("    AppBuilder::new()\n");
        code.push_str("        .with_title(\"My App\")\n");
        code.push_str("        .with_ui(|ui| {\n");
        
        for widget in &scene.widgets {
            code.push_str(&self.generate_widget_builder(widget, config));
        }
        
        code.push_str("        })\n");
        code.push_str("        .run();\n");
        code.push_str("}\n");
        
        Ok(code)
    }
    
    fn generate_plugins(&self, scene: &SceneState, config: &CodegenConfig) -> Result<String, PluginError> {
        let mut code = String::new();
        
        if config.include_comments {
            code.push_str(&format!("// Generated by GUIMaker\n"));
            code.push_str(&format!("// Format: Plugins\n\n"));
        }
        
        code.push_str("use ferrous_plugin::{Plugin, PluginContext};\n");
        code.push_str("use ferrous_gui::{Widget, Ui};\n\n");
        
        code.push_str("pub struct MyAppPlugin;\n\n");
        code.push_str("impl Plugin for MyAppPlugin {\n");
        code.push_str("    fn id(&self) -> &'static str { \"my-app\" }\n");
        code.push_str("    fn name(&self) -> &'static str { \"My App Plugin\" }\n");
        code.push_str("    fn version(&self) -> &'static str { \"1.0.0\" }\n");
        code.push_str("    fn initialize(&self, ctx: &mut PluginContext) -> Result<(), PluginError> {\n");
        
        for widget in &scene.widgets {
            code.push_str(&format!("        // Register widget: {}\n", widget.kind.display_name()));
        }
        
        code.push_str("        Ok(())\n");
        code.push_str("    }\n");
        code.push_str("}\n");
        
        Ok(code)
    }
    
    fn generate_multi_file(&self, scene: &SceneState, config: &CodegenConfig) -> Result<String, PluginError> {
        let mut code = String::new();
        
        if config.include_comments {
            code.push_str(&format!("// Generated by GUIMaker\n"));
            code.push_str(&format!("// Format: MultiFile\n\n"));
            code.push_str("// This would generate multiple files:\n");
            code.push_str("// - main.rs: Entry point\n");
            code.push_str("// - ui.rs: UI components\n");
            code.push_str("// - events.rs: Event handlers\n");
            code.push_str("// - state.rs: Application state\n\n");
        }
        
        code.push_str("// Multi-file generation would be implemented here\n");
        code.push_str("// Each file would be generated separately\n");
        
        Ok(code)
    }
    
    fn generate_imports(&self, scene: &SceneState, config: &CodegenConfig) -> String {
        let mut imports = String::new();
        
        imports.push_str("use ferrous_engine::{App, AppContext, AppMode, Color, FerrousApp, KeyCode};\n");
        imports.push_str("use ferrous_assets::Font;\n");
        
        let mut gui_types = vec!["GuiBatch", "TextBatch", "Ui"];
        
        for widget in &scene.widgets {
            match widget.kind {
                WidgetKind::Button => gui_types.push("Button"),
                WidgetKind::Slider => gui_types.push("Slider"),
                WidgetKind::Checkbox => gui_types.push("Checkbox"),
                WidgetKind::TextInput => gui_types.push("TextInput"),
                WidgetKind::ProgressBar => gui_types.push("ProgressBar"),
                WidgetKind::DropDown => gui_types.push("Dropdown"),
                _ => {}
            }
        }
        
        imports.push_str(&format!("use ferrous_gui::{{{}}};\n", gui_types.join(", ")));
        imports.push_str("\n");
        
        imports
    }
    
    fn generate_struct(&self, scene: &SceneState, config: &CodegenConfig) -> String {
        let mut struct_def = String::new();
        
        let struct_name = "MyApp"; // Simplified for now
        
        struct_def.push_str(&format!("struct {} {{\n", struct_name));
        
        for widget in &scene.widgets {
            let var_name = format!("{}_{}", widget.kind.display_name().to_lowercase(), widget.id);
            let type_name = self.widget_type_name(widget.kind);
            
            struct_def.push_str(&format!("    {}: {},\n", var_name, type_name));
        }
        
        struct_def.push_str("}\n\n");
        
        struct_def
    }
    
    fn generate_default(&self, scene: &SceneState, config: &CodegenConfig) -> String {
        let mut default_impl = String::new();
        
        default_impl.push_str("impl Default for MyApp {\n");
        default_impl.push_str("    fn default() -> Self {\n");
        default_impl.push_str("        Self {\n");
        
        for widget in &scene.widgets {
            let var_name = format!("{}_{}", widget.kind.display_name().to_lowercase(), widget.id);
            
            match widget.kind {
                WidgetKind::Button => {
                    default_impl.push_str(&format!(
                        "            {}: Button::new({:.1}, {:.1}, {:.1}, {:.1}),\n",
                        var_name, widget.x, widget.y, widget.w, widget.h
                    ));
                }
                WidgetKind::Slider => {
                    default_impl.push_str(&format!(
                        "            {}: Slider::new({:.1}, {:.1}, {:.1}, {:.1}, {:.2}),\n",
                        var_name, widget.x, widget.y, widget.w, widget.h, widget.props.value
                    ));
                }
                // Add other widget types...
                _ => {
                    default_impl.push_str(&format!(
                        "            {}: {}::new(),\n",
                        var_name, self.widget_type_name(widget.kind)
                    ));
                }
            }
        }
        
        default_impl.push_str("        }\n");
        default_impl.push_str("    }\n");
        default_impl.push_str("}\n\n");
        
        default_impl
    }
    
    fn generate_ferrous_engine_impl(&self, scene: &SceneState, config: &CodegenConfig) -> String {
        let mut impl_app = String::new();
        
        impl_app.push_str("impl FerrousApp for MyApp {\n");
        impl_app.push_str("    fn configure_ui(&mut self, ui: &mut Ui) {\n");
        
        for widget in &scene.widgets {
            if widget.kind != WidgetKind::Label && 
               widget.kind != WidgetKind::Panel && 
               widget.kind != WidgetKind::Separator {
                let var_name = format!("{}_{}", widget.kind.display_name().to_lowercase(), widget.id);
                impl_app.push_str(&format!("        ui.add(self.{}.clone());\n", var_name));
            }
        }
        
        impl_app.push_str("    }\n\n");
        
        impl_app.push_str("    fn update(&mut self, ctx: &mut AppContext) {\n");
        impl_app.push_str("        if ctx.input.just_pressed(KeyCode::Escape) {\n");
        impl_app.push_str("            ctx.request_exit();\n");
        impl_app.push_str("        }\n");
        impl_app.push_str("    }\n\n");
        
        impl_app.push_str("    fn draw_ui(\n");
        impl_app.push_str("        &mut self,\n");
        impl_app.push_str("        gui: &mut GuiBatch,\n");
        impl_app.push_str("        text: &mut TextBatch,\n");
        impl_app.push_str("        font: Option<&Font>,\n");
        impl_app.push_str("        _ctx: &mut AppContext,\n");
        impl_app.push_str("    ) {\n");
        
        for widget in &scene.widgets {
            let var_name = format!("{}_{}", widget.kind.display_name().to_lowercase(), widget.id);
            
            match widget.kind {
                WidgetKind::Label => {
                    impl_app.push_str(&format!(
                        "        text.add_text(font, \"{}\", {:.1}, {:.1});\n",
                        widget.props.label, widget.x, widget.y
                    ));
                }
                WidgetKind::Button | WidgetKind::Slider | WidgetKind::Checkbox | 
                WidgetKind::TextInput | WidgetKind::ProgressBar | WidgetKind::DropDown => {
                    impl_app.push_str(&format!("        self.{}.draw(gui);\n", var_name));
                }
                _ => {}
            }
        }
        
        impl_app.push_str("    }\n");
        impl_app.push_str("}\n\n");
        
        impl_app
    }
    
    fn generate_main(&self, scene: &SceneState, config: &CodegenConfig) -> String {
        let mut main_fn = String::new();
        
        main_fn.push_str("fn main() {\n");
        main_fn.push_str("    App::new(MyApp::default())\n");
        main_fn.push_str("        .with_title(\"My App\")\n");
        main_fn.push_str("        .with_size(1280, 720)\n");
        main_fn.push_str("        .with_mode(AppMode::Desktop2D)\n");
        main_fn.push_str("        .with_background_color(Color::rgb(0.10, 0.10, 0.12))\n");
        main_fn.push_str("        .with_font(\"assets/fonts/Roboto-Regular.ttf\")\n");
        main_fn.push_str("        .run();\n");
        main_fn.push_str("}\n");
        
        main_fn
    }
    
    fn generate_widget_builder(&self, widget: &crate::scene::PlacedWidget, config: &CodegenConfig) -> String {
        let mut builder = String::new();
        
        builder.push_str(&format!("            // {}\n", widget.kind.display_name()));
        builder.push_str(&format!("            ui.add(Widget::new(\"{}\"));\n", widget.kind.display_name()));
        
        builder
    }
    
    fn widget_type_name(&self, kind: WidgetKind) -> &'static str {
        match kind {
            WidgetKind::Button => "Button",
            WidgetKind::Slider => "Slider",
            WidgetKind::Checkbox => "Checkbox",
            WidgetKind::TextInput => "TextInput",
            WidgetKind::ProgressBar => "ProgressBar",
            WidgetKind::DropDown => "Dropdown",
            WidgetKind::Label => "Label",
            WidgetKind::Panel => "Panel",
            WidgetKind::Separator => "Separator",
            WidgetKind::Image => "Image",
            _ => "Widget",
        }
    }
}