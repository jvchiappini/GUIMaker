//! Modular code generation system for GUIMaker
//!
//! This module provides a plugin-based, template-driven code generation system
//! that supports multiple output formats and customizable generation strategies.

use crate::plugin::{CodegenConfig, CodegenGenerator, OutputFormat, PluginError};
use crate::scene::SceneState;
use crate::template::{TemplateEngine, TemplateRegistryRef};
/// Modular code generator that integrates with plugins and templates
pub struct ModularCodegen {
    template_engine: TemplateEngine,
    plugin_generators: std::collections::HashMap<OutputFormat, Box<dyn CodegenGenerator>>,
}

impl ModularCodegen {
    pub fn new(template_registry: TemplateRegistryRef) -> Self {
        Self {
            template_engine: TemplateEngine::new(template_registry),
            plugin_generators: std::collections::HashMap::new(),
        }
    }
    
    /// Register a plugin-based code generator
    pub fn register_generator(
        &mut self,
        format: OutputFormat,
        generator: Box<dyn CodegenGenerator>,
    ) -> Result<(), PluginError> {
        let key = format.clone();
        if self.plugin_generators.contains_key(&key) {
            return Err(PluginError::AlreadyRegistered(format!("{:?}", format)));
        }
        self.plugin_generators.insert(key, generator);
        Ok(())
    }
    
    /// Generate code using the appropriate generator
    /// Returns a String (empty on error) to maintain compatibility with existing code
    pub fn generate(
        &self,
        scene: &SceneState,
        config: &CodegenConfig,
        project_name: &str,
    ) -> String {
        // Try plugin generator first
        if let Some(generator) = self.plugin_generators.get(&config.output_format) {
            match generator.generate(scene, config) {
                Ok(code) => return code,
                Err(e) => eprintln!("Plugin generator error: {}", e),
            }
        }
        
        // Fall back to template-based generation
        match self.generate_from_template(scene, config, project_name) {
            Ok(code) => code,
            Err(e) => {
                eprintln!("Template generation error: {}", e);
                format!("// Error generating code: {}", e)
            }
        }
    }
    
    /// Generate code using template system
    fn generate_from_template(
        &self,
        scene: &SceneState,
        config: &CodegenConfig,
        project_name: &str,
    ) -> Result<String, PluginError> {
        // This would integrate with the template system to generate code
        // For now, return a basic template-based generation
        let mut code = String::new();
        
        code.push_str(&format!("// Generated by GUIMaker Modular Codegen\n"));
        code.push_str(&format!("// Project: {}\n", project_name));
        code.push_str(&format!("// Format: {:?}\n\n", config.output_format));
        
        // Add basic structure based on scene
        code.push_str(&self.generate_basic_structure(scene, config));
        
        Ok(code)
    }
    
    /// Generate basic code structure
    fn generate_basic_structure(&self, scene: &SceneState, config: &CodegenConfig) -> String {
        let mut code = String::new();
        
        // Generate imports based on config
        if config.include_comments {
            code.push_str("// Imports\n");
        }
        
        match config.output_format {
            OutputFormat::FerrousApp => {
                code.push_str("use ferrous_engine::{App, AppContext, AppMode, Color, FerrousApp, KeyCode};\n");
                code.push_str("use ferrous_assets::Font;\n");
                code.push_str("use ferrous_gui::{GuiBatch, TextBatch, Ui};\n\n");
            }
            OutputFormat::AppBuilder => {
                code.push_str("use ferrous_engine::AppBuilder;\n");
                code.push_str("use ferrous_gui::{Widget, UiBuilder};\n\n");
            }
            OutputFormat::Plugins => {
                code.push_str("use ferrous_plugin::{Plugin, PluginContext};\n");
                code.push_str("use ferrous_gui::{Widget, Ui};\n\n");
            }
            OutputFormat::MultiFile => {
                code.push_str("// Multi-file output would be generated here\n");
                code.push_str("// main.rs, ui.rs, events.rs, state.rs\n\n");
            }
        }
        
        code
    }
    
    /// Get available output formats
    pub fn available_formats(&self) -> Vec<OutputFormat> {
        let mut formats = vec![OutputFormat::FerrousApp, OutputFormat::AppBuilder, OutputFormat::Plugins, OutputFormat::MultiFile];
        formats.extend(self.plugin_generators.keys().cloned());
        formats
    }
}